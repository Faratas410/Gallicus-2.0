def preview(path: Path, audio: np.ndarray) -> None:
    dsp.write_wav(path, audio)


def momentary_peak(x: np.ndarray) -> float:
    """Loudest 300 ms window, in dB RMS: how loud a short cue feels."""
    power = (x.astype(np.float64) ** 2).mean(axis=1)
    window = int(0.3 * SR)
    if len(power) <= window:
        return 10 * np.log10(power.mean() + 1e-12)
    running = np.convolve(power, np.ones(window) / window, "valid")
    return float(10 * np.log10(running.max() + 1e-12))


def finish_cue(x: np.ndarray, family: str, max_seconds: float | None = None) -> np.ndarray:
    if family != "terminal":  # the heartbeat keeps its full three-second period
        level = np.abs(x).max(axis=1)
        last = len(level) - int(np.argmax(level[::-1] > level.max() * db(-56)))
        x = dsp.fade(x[: min(len(x), last + int(0.03 * SR))], 0.001, 0.03)
    if max_seconds is not None and len(x) > max_seconds * SR:
        x = dsp.fade(x[: int(max_seconds * SR)], 0.0, min(0.22, 0.3 * max_seconds))
    x = dsp.highpass(x, 40)
    x = x * db(cues.LEVELS[family] - momentary_peak(x))
    x = dsp.soft_limit(x, -3.0)
    x[0] = 0.0
    x[-1] = 0.0
    return x


def compose_sfx(preview_dir) -> dict:
    entries = {}
    for name, (builder, family, recipe, is_stereo) in cues.build_cues(None).items():
        rng = np.random.default_rng(zlib.crc32(name.encode()))
        audio = finish_cue(builder(rng), family, cues.MAX_SECONDS.get(name))
        if not is_stereo:
            audio = np.repeat(audio.mean(axis=1, keepdims=True), 2, axis=1)
        path = ROOT / f"assets/audio/sfx/{name}.wav"
        dsp.write_wav(path, audio, mono=not is_stereo)
        res = f"res://assets/audio/sfx/{name}.wav"
        entries[res] = {"path": res, "role": "sfx", "family": family, "recipe": recipe,
                        "seconds": round(len(audio) / SR, 4), "sample_rate": SR, "channels": 2 if is_stereo else 1,
                        **stats(audio), "sha256": hashlib.sha256(path.read_bytes()).hexdigest()}
        print(f"[OK] {name}: {len(audio) / SR:.2f}s {entries[res]['peak_dbfs']} dBFS")
        if preview_dir:
            preview(Path(preview_dir) / "sfx" / f"{name}.wav", audio)
    return entries


