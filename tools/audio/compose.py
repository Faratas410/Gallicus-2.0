def timpani(m: int) -> np.ndarray:
    return dsp.pitch(hit("timp_Timpani3_Hit_v3_rr1"), m - (midi("D2") - 0.58))


def stem_mix(stems: dict, levels: dict, ir) -> np.ndarray:
    """Render each stem as a loop, set it to its LUFS level, sum, master."""
    total = None
    for name, bus in stems.items():
        audio = bus.render(ir, loop=True) if isinstance(bus, Bus) else bus
        audio = dsp.to_lufs(audio, levels[name])
        total = audio if total is None else total + audio
    total = dsp.highpass(total, 32)
    return master(total, -18.0)


def master(x: np.ndarray, target_lufs: float) -> np.ndarray:
    x = dsp.to_lufs(x, target_lufs)
    x = dsp.soft_limit(x, -1.5)
    return x


def loop_drone(seed: int) -> np.ndarray:
    d = drone(LOOP + 2.0, seed)
    # Crossfade the extra two seconds over the start: the drone loops cleanly.
    head = d[: int(2.0 * SR)]
    tail = d[int(LOOP * SR): int(LOOP * SR) + len(head)]
    ramp = np.linspace(0, 1, len(head))[:, None]
    body = d[: int(LOOP * SR)].copy()
    body[: len(head)] = head * ramp + tail * (1 - ramp)
    return body


def score_atrium(rng, ir):
    harp_bus, mel, perc, air = Bus(LOOP), Bus(LOOP), Bus(LOOP), Bus(LOOP)
    harp(harp_bus, "sparse", rng, soft=True)
    melody(mel, THEME_A, 8, rng)
    melody(mel, THEME_B, 16, rng)
    for bar in range(0, BARS, 2):
        perc.add(hit("frame_HDrumL_Hit_v2_rr1"), bar * BAR, -2, 0.0, -10)
        if bar % 4 == 2:
            perc.add(hit("frame_HDrumL_Hand_rr1"), bar * BAR + 2.5 * BEAT, -10, -0.2, -8)
    perc.add(hit("handbell_HB_1"), 0.0, -6, 0.3, -4)
    perc.add(hit("handbell_HB_2"), 12 * BAR, -9, -0.3, -4)
    wind = dsp.lowpass(dsp.sustain(dsp.load("ocean_drum_2"), LOOP, 7, grain=2.0, start=1.0, end_margin=1.0), 900)
    air.add(wind, 0.0, 0, 0.0, -6)
    stems = {"harp": harp_bus, "melody": mel, "perc": perc, "air": air, "drone": loop_drone(11)}
    levels = {"harp": -20, "melody": -24, "perc": -27, "air": -36, "drone": -29}
    return stem_mix(stems, levels, ir)


