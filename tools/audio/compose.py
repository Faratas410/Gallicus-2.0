# --- the gradinata -------------------------------------------------------

VOWELS = {  # formant centre frequencies (Hz) for a neutral adult voice
    "a": (750, 1200, 2500), "e": (480, 1800, 2550), "i": (320, 2200, 2900),
    "o": (500, 900, 2400), "u": (350, 800, 2300), "@": (550, 1500, 2450),
}


def voice(seconds: float, rng, f0: float) -> np.ndarray:
    """One distant speaker: a glottal buzz shaped into syllables and pauses."""
    n = int(seconds * SR)
    out = np.zeros(n, dtype=np.float32)
    t = 0.0
    while t < seconds:
        talk = rng.uniform(0.8, 3.2)
        end = min(seconds, t + talk)
        while t < end:
            syllable = rng.uniform(0.12, 0.28)
            count = int(syllable * SR)
            start = int(t * SR)
            if start + count >= n:
                break
            pitch_curve = f0 * (1 + 0.06 * rng.standard_normal()) * np.linspace(1.0, rng.uniform(0.9, 1.08), count)
            phase = np.cumsum(pitch_curve / SR)
            buzz = 2 * (phase % 1.0) - 1 + 0.15 * rng.standard_normal(count)
            formants = VOWELS[rng.choice(list(VOWELS))]
            shaped = np.zeros(count, dtype=np.float32)
            for index, centre in enumerate(formants):
                low, high = centre * 0.85, centre * 1.15
                band = dsp.bandpass(buzz[:, None], low, high, order=1)[:, 0]
                shaped += band * (1.0, 0.5, 0.2)[index]
            envelope = np.sin(np.linspace(0, np.pi, count)) ** 0.7
            out[start: start + count] += shaped * envelope * rng.uniform(0.5, 1.0)
            t += syllable * rng.uniform(0.85, 1.05)
        t = end + rng.uniform(0.3, 2.2)
    return out


def murmur(seconds: float, rng, voices: int = 26) -> np.ndarray:
    out = np.zeros((int(seconds * SR), 2), dtype=np.float32)
    for _ in range(voices):
        v = voice(seconds, rng, rng.choice([rng.uniform(95, 140), rng.uniform(170, 240)]))
        out += dsp.balance(dsp.stereo(v), rng.uniform(-1, 1)) * db(rng.normal(0, 3))
    # Thicken the stand: the same crowd a little lower and later, a little higher and earlier.
    thick = out.copy()
    for semis, shift in ((-2.0, 0.37), (1.5, 0.71)):
        moved = np.roll(dsp.pitch(out, semis), int(shift * len(out)), axis=0)[: len(out)]
        thick[: len(moved)] += dsp.width(moved, -1.0) * 0.8
    return dsp.lowpass(dsp.highpass(thick, 140), 2600)


def loop_bus_from(audio: np.ndarray) -> np.ndarray:
    """Crossfade a longer render onto itself for a seamless loop of LOOP length."""
    n = int(LOOP * SR)
    extra = len(audio) - n
    body = audio[:n].copy()
    ramp = np.linspace(0, 1, extra)[:, None]
    body[:extra] = audio[:extra] * ramp + audio[n: n + extra] * (1 - ramp)
    return body


def crowd_murmur(rng, ir):
    """Gradinata at rest: talk, shuffling feet on sand, torches."""
    talk = loop_bus_from(murmur(LOOP + 4.0, rng))
    bed = Bus(LOOP)
    bed.add(talk, 0.0, 0, 0.0, -2)
    fire = dsp.sustain(dsp.load("mt_fire_1"), LOOP, 3, grain=1.2, start=0.2, end_margin=0.3)
    bed.add(dsp.lowpass(fire, 3000), 0.0, -22, -0.6, -12)
    for _ in range(int(LOOP * 1.2)):
        at = rng.uniform(0, LOOP)
        step = dsp.pitch(hit(FOOT[int(rng.integers(3))]), rng.normal(-4, 1.5))
        bed.add(dsp.lowpass(step, 2500), at, rng.normal(-24, 3), rng.uniform(-1, 1), -4)
    for _ in range(14):
        bed.add(dsp.lowpass(hit(CLAPS[int(rng.integers(len(CLAPS)))]), 4000), rng.uniform(0, LOOP), rng.normal(-26, 3), rng.uniform(-1, 1), -2)
    audio = bed.render(ir, loop=True)
    return master(dsp.highpass(audio, 60), -24.0)


def crowd_rhythm(rng, ir):
    """Gradinata pressing: stomps on 1 and 3, claps on 2 and 4, voices rising."""
    bus = Bus(LOOP)
    for bar in range(BARS):
        for beat in (0, 2):
            bus.add(crowd_stomp(14, rng), bar * BAR + beat * BEAT, 0, 0.0, -4)
        for beat in (1, 3):
            bus.add(crowd_clap(16, rng), bar * BAR + beat * BEAT, -1, 0.0, -3)
    talk = loop_bus_from(murmur(LOOP + 4.0, rng, voices=20))
    bus.add(dsp.peak_eq(talk, 900, 4.0, 0.8), 0.0, -6, 0.0, -4)
    audio = bus.render(ir, loop=True)
    return master(dsp.highpass(audio, 45), -22.0)


