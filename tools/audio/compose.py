ROOT = Path(__file__).resolve().parents[2]
BPM = 72.0
BEAT = 60.0 / BPM
BAR = 4 * BEAT
BARS = 24
LOOP = BARS * BAR  # 80 s
SIXTEENTH = BEAT / 4

# D Dorian: the open D/A of the previous "Pietra e Aria" set, with the raised
# sixth (B) as the arena's colour.
CHORDS = {
    "Dm": ("D", ["D", "F", "A"]),
    "C": ("C", ["C", "E", "G"]),
    "G": ("G", ["G", "B", "D"]),
    "Am": ("A", ["A", "C", "E"]),
    "F": ("F", ["F", "A", "C"]),
}
PROGRESSION = [
    "Dm", "Dm", "C", "Dm", "Dm", "G", "Am", "Dm",
    "F", "C", "Dm", "Dm", "G", "Am", "C", "Dm",
    "Dm", "C", "Dm", "G", "F", "Am", "Dm", "Dm",
]
# The Gallicus theme: (beat offset inside the phrase, note, length in beats).
THEME_A = [(0, "A4", 2), (2, "G4", 1), (3, "F4", 1), (4, "E4", 1), (5, "F4", 1), (6, "D4", 2),
           (8, "C4", 1), (9, "D4", 1), (10, "E4", 1), (11, "G4", 1), (12, "D4", 4)]
THEME_B = [(0, "D5", 2), (2, "C5", 1), (3, "A4", 1), (4, "B4", 2), (6, "A4", 2),
           (8, "G4", 1), (9, "A4", 1), (10, "F4", 1), (11, "E4", 1), (12, "D4", 4)]


class Sampler:
    """Nearest-sample pitched instrument. VCSL names sit one octave low."""

    def __init__(self, prefix: str, names: list[str], suffix: str = "", octave_fix: int = 12):
        self.zones = [(midi(n) + octave_fix, f"{prefix}{n}{suffix}") for n in names]

    def note(self, m: int) -> np.ndarray:
        actual, key = min(self.zones, key=lambda zone: (abs(zone[0] - m), zone[0] < m))
        return dsp.shifted(key, m - actual)


def octave_names(pcs: list[str], octaves: list[int]) -> list[str]:
    return [f"{pc}{o}" for o in octaves for pc in pcs]


HARP_NAMES = octave_names(["C", "D", "E", "F#", "G#", "A#"], [2, 3, 4]) + ["C5", "D5", "E5"]
HARP_LOUD = Sampler("harp_", HARP_NAMES, "_v3")
HARP_SOFT = Sampler("harp_", HARP_NAMES, "_v2")
RECORDER = Sampler("tenrec_", ["C3", "D3", "E3", "F#3", "G3", "A3", "B3", "C4", "D4", "E4", "F#4", "G4", "A4", "B4"])
PSALTERY = Sampler("psaltery_bow_", ["C4", "D4", "E4", "F#4", "G#4", "A#4", "C5", "D5"])


def hit(key: str, peak_db: float = -1.0) -> np.ndarray:
    """A percussion one-shot normalised to a common peak, so velocity is ours."""
    return dsp.peak_to(dsp.load(key), peak_db)


def chord_tones(name: str) -> list[int]:
    root, pcs = CHORDS[name]
    r3 = midi(f"{root}3")
    third = (dsp.NOTE_PC[pcs[1]] - dsp.NOTE_PC[root]) % 12
    fifth = (dsp.NOTE_PC[pcs[2]] - dsp.NOTE_PC[root]) % 12
    if r3 > midi("A3"):
        r3 -= 12
    return [r3, r3 + fifth, r3 + 12, r3 + 12 + third, r3 + 12 + fifth, r3 + 24]


HARP_PATTERNS = {
    "sparse": [[(0, 0, 0.0), (4, 2, -4), (8, 3, -3), (12, 4, -5)],
               [(0, 0, 0.0), (6, 4, -4), (10, 3, -6)],
               [(0, 0, 0.0), (4, 1, -4), (8, 2, -3), (11, 3, -6), (14, 4, -7)]],
    "flow": [[(0, 0, 0.0), (2, 1, -5), (4, 2, -3), (6, 3, -4), (8, 4, -2), (10, 3, -5), (12, 2, -4), (14, 1, -6)],
             [(0, 0, 0.0), (2, 2, -5), (4, 3, -3), (6, 4, -4), (8, 5, -2), (10, 4, -5), (12, 3, -4), (14, 2, -6)]],
    "ostinato": [[(0, 0, 0.0), (2, 2, -4), (3, 1, -7), (4, 2, -4), (6, 0, -2), (8, 2, -4), (10, 1, -6), (11, 2, -7), (12, 4, -3), (14, 2, -5)]],
}


def harp(bus: Bus, style: str, rng, bars=range(BARS), gain=0.0, soft=False, send=-8.0, octave=0):
    for bar in bars:
        tones = [t + octave for t in chord_tones(PROGRESSION[bar])]
        patterns = HARP_PATTERNS[style]
        pattern = patterns[(bar + (bar // 4)) % len(patterns)]
        for step, tone, vel in pattern:
            at = bar * BAR + step * SIXTEENTH + rng.normal(0, 0.008)
            sampler = HARP_SOFT if soft or vel < -5 else HARP_LOUD
            pan = -0.35 + 0.7 * (tone / 5)
            bus.add(sampler.note(tones[tone]), at, gain + vel + rng.normal(0, 1.0), pan, send)


def melody(bus: Bus, phrase, start_bar: float, rng, transpose=0, gain=0.0, stretch=1.0, send=-6.0, pan=0.1):
    for beat, name, length in phrase:
        m = midi(name) + transpose
        seconds = length * BEAT * stretch
        tone = RECORDER.note(m)
        if seconds + 0.3 > len(tone) / SR - 0.5:
            tone = np.concatenate([tone[: int(0.4 * SR)], dsp.sustain(tone, seconds, seed=m)])
        note = dsp.cut(tone, seconds * 0.96, release=0.22)
        note = dsp.fade(note, 0.04, 0.0)
        at = start_bar * BAR + beat * BEAT * stretch + rng.normal(0, 0.01)
        bus.add(note, at, gain + rng.normal(0, 0.6), pan, send)


def drone(seconds: float, seed: int) -> np.ndarray:
    """Low D and A from the bass recorder: the 'aria' that holds the arena."""
    low_d = dsp.sustain(dsp.pitch(dsp.load("bassrec_D3"), -12), seconds, seed, grain=0.9)
    a = dsp.sustain(dsp.load("bassrec_A2"), seconds, seed + 1, grain=0.9)
    t = np.arange(len(low_d)) / SR
    breath = (0.75 + 0.25 * np.sin(2 * np.pi * t / (LOOP / 4)))[:, None]
    mix = dsp.lowpass(low_d * 1.0 + a * 0.55, 1400) * breath
    return dsp.width(mix, 1.4)


def pad(bus: Bus, bars, rng, gain=0.0, send=-3.0):
    """Bowed psaltery an octave down: thirds and fifths of each chord, held."""
    for bar in bars:
        tones = chord_tones(PROGRESSION[bar])
        for index, tone in enumerate([tones[3], tones[4]]):
            m = tone + 12
            note = dsp.cut(dsp.pitch(PSALTERY.note(m), -12), BAR * 1.05, release=0.8)
            bus.add(dsp.fade(note, 0.5, 0.0), bar * BAR + 0.05 * index, gain + rng.normal(0, 0.8), -0.4 + 0.8 * index, send)


def pattern_hits(bus: Bus, grid: str, bars, sounds: dict, rng, gain=0.0, send=-14.0, swing=0.0):
    """grid: 16 steps per bar; each letter picks a sound, '.' is a rest."""
    for bar in bars:
        for step, letter in enumerate(grid):
            if letter == ".":
                continue
            key, level, pan = sounds[letter]
            choice = key[int(rng.integers(len(key)))] if isinstance(key, list) else key
            late = swing * SIXTEENTH if step % 2 else 0.0
            at = bar * BAR + step * SIXTEENTH + late + rng.normal(0, 0.006)
            bus.add(hit(choice), at, gain + level + rng.normal(0, 1.2), pan, send)


CLAPS = [f"clap_Clap_rr{i}" for i in range(1, 7)] + [f"clap_SoloClap_vl{i}" for i in range(2, 5)]


def crowd_clap(people: int, rng, spread: float = 0.035) -> np.ndarray:
    """Many hands at once: layered claps with human scatter, darkened by distance."""
    out = dsp.silence(1.2)
    for _ in range(people):
        clap = dsp.pitch(hit(CLAPS[int(rng.integers(len(CLAPS)))]), rng.normal(0, 1.2))
        start = int(abs(rng.normal(0, spread)) * SR)
        piece = dsp.balance(clap, rng.uniform(-0.9, 0.9))[: len(out) - start] * db(rng.normal(-3, 2.5))
        out[start: start + len(piece)] += piece
    return dsp.lowpass(out, 5200) / np.sqrt(people)


FOOT = ["mt_sand_footstep_1", "mt_sand_footstep_2", "mt_sand_footstep_3",
        "mt_hard_footstep_1", "mt_hard_footstep_2", "mt_hard_footstep_3"]


def crowd_stomp(people: int, rng, spread: float = 0.03) -> np.ndarray:
    """Feet on the stone steps: a soft drum body under many real footsteps."""
    out = dsp.silence(1.5)
    body = dsp.lowpass(hit("bassdrum_bassdrum_hit_mp1"), 180)[: int(1.4 * SR)]
    out[: len(body)] += body * db(-4)
    for _ in range(people):
        step = dsp.pitch(hit(FOOT[int(rng.integers(len(FOOT)))]), rng.normal(-3, 1.5))
        start = int(abs(rng.normal(0, spread)) * SR)
        piece = dsp.balance(step, rng.uniform(-0.9, 0.9))[: len(out) - start] * db(rng.normal(-6, 2.5))
        out[start: start + len(piece)] += piece
    return dsp.lowpass(out, 3500) / np.sqrt(people / 3)


