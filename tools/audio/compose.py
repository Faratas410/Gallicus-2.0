"""Compose Gallicus' score, the gradinata and the ritual cues.

Usage:
    python tools/audio/fetch_sources.py
    python tools/audio/compose.py [--cache DIR] [--only music|crowd|sfx] [--preview DIR]

Every sound is built from the recordings pinned in tools/audio/sources.json
(CC0, plus a few CC-BY 3.0 recordings credited in docs/audio_credits.md):
harp, psaltery, recorders, frame drum, darbuka, timpani, gong, bells, claps,
sand, gravel, metal and fire. The script picks, trims, pitches, layers and
mixes them; nothing is generated by a neural model. Output:

- assets/audio/score/*.ogg   five seamless 80 s loops at 72 BPM in D Dorian
                             and two gradinata beds (murmur, rhythm)
- assets/audio/sfx/*.wav     ritual cues, mono PCM16 44.1 kHz
- assets/audio/manifest.json path, role, recipe, sources, loudness, sha256
"""
